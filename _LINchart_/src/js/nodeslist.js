/**
 * Generate widget to show actual list of persons in view
 * - optionally defined focus_node
 * - list of names in data -> check/uncheck to put in/remove from filter_list
 */
function showNODES() {
    nodeMagnifier = parms.lGET("nodeMagnifier");
    nodeHighlighter = nodeMagnifier - 0.01;
    
    // set html for filter-management
    let ovHTML = html_nodeslist();
    let OVelmnt = document.getElementById("nodeslist");
    OVelmnt.innerHTML = ovHTML;
    // get the actual defined list of names
    // const menu_nodeslist = document.getElementById("menu_nodeslist");

    // initialize parms for controlling menu_nodeslist and filterA
    parms.lSET("fAind",0);
    parms.lSET("doShow_nol", false);

    // define events on action-elements in widget
    // -Schliessen-
    d3.select(".fh-close").on("click", function(event) {
        parms.lSET("loop_filter", false);
        close_nodeslist(event);
    });
    // -Speichern-
    d3.select(".fh-ok").on("click", function(event) {
        save_namefilter();
        close_nodeslist(event);
        parms.lSET("loop_filter", false);
    });

    showNODES_nol();

    let win_iH = window.innerHeight;
    win_iH -= 256; let _win_iH = win_iH.toString();
    let nl_ul = document.getElementById('nodes_liLines');
    nl_ul.setAttribute('style', 'height:' + _win_iH + 'px');

    // Reset Focus_Node
        // Click is done on child element, therefore event will only be done when bubbling happens ...
    d3.select("#nodes_sel button")
        .on("click", function(event) {
            if (event.eventPhase == 3) {          // Click on button -> eventPhase == 3 - event.BUBBLING_PHASE
                let efN = event.target;
                do {
                    if (efN.classList.contains('btn'))
                        break;
                    efN = efN.parentNode;
                } while (!efN.classList.contains('btn'));
                efN = efN.previousElementSibling;
                let fN_key = efN.textContent;
                efN.textContent = i18n('nol_placeholder');
                efN.classList.add('placeholder');
                let Focus_Node = C_NODESman.Focus_Node;
                if (Focus_Node) {
                    Focus_Node.sr = 1; Focus_Node.fx = null; Focus_Node.fy = null; Focus_Node.is_focus = false;
                }
                C_NODESman.Focus_Node = null;
                let efNl = nl_ul.getElementsByClassName('nol-focus-node');
                if (efNl) { efNl[0].classList.toggle('nol-focus-node'); }
                event.preventDefault();
            } else {
                event.stopPropagation();
            }
        })

    // Add click-event to nodes_liLines to highlight selected line and corresponding node in viewport
        // Click is done on child element, therefore event will only be done when bubbling happens ...
        // Click-event will also occur when resizing element itsself, but then eventPhase == 2 - event.AT_TARGET
    d3.select("#nodes_liLines")
        .on("click", function(event) {
            if (event.target.tagName == "LI") {
                if (event.eventPhase == 3) {          // Click on li -> eventPhase == 3 - event.BUBBLING_PHASE
                    NodeList_click(event);
                    event.preventDefault();
                }
            }
            event.stopPropagation();
        })
        .on("dblclick", function(event) {
            if (event.eventPhase == 3) {          // Click on li -> eventPhase == 3 - event.BUBBLING_PHASE
                NodeList_dblclick(event);
                event.preventDefault();
            } else {
                event.stopPropagation();
            }
        });

    showNODES_ul_li();

    // Reset highlighted selected lines in nodes_liLines and correponding nodes in viewport
    d3.select("#clearSI")
        .on("click", function(event) {
            if (cnt_sel_ID < 1) return false;
            let uli_sID = Array.from(document.getElementsByClassName("nol-ulli selectedID"));
            for (let _uli of uli_sID) {
                _uli.classList.remove("selectedID");
                let nKey = _uli.textContent;
                let Ynode = C_NODESman.get_Ynodes(nKey);
                if (Ynode.is_focus) {
                    make_Focus_Node(Ynode);
                } else {
                    if (Ynode.sr == nodeMagnifier) {
                        Ynode.sr = 1; Ynode.fx = null; Ynode.fy = null;
                    }
                }
                switch_clearSI(-1);
            }
        });

    let nodes_list_form = document.getElementById("nodeslist");
    drag_nol(nodes_list_form);
}
function showNODES_ul_li() {
    // Add Hover sensitivity to nodes_liLines
    d3.selectAll(".nol-ulli")
        .on("mouseenter", function(event) {
            if (event.eventPhase == 2) {
                showNODES_lme(event);
                event.preventDefault();
            } else {
                event.stopPropagation();
            }
        })
        .on("mouseout", function(event) {
            if (event.eventPhase == 2) {
                showNODES_lmo(event);
                event.preventDefault();
            } else {
                event.stopPropagation();
            }
        });

}
/**
 * Namens-Liste zu gewähltem Filter anzeigen
 * 'nodes_list' -> Liste als Map - sortiert nach Anzahl
 * 'C_liHead'   -> Listenkopf
 *                 - wird nur gezeigt, wenn mehr als X Personen in Liste -> parm NODES_LIST_size
 * 'C_liLines'  -> Listen-Einträge
 *                  Namen
 * Steuerung:   nol-Type        "NLc"     list by names | "NLy"      list by years
 *              nol-Sort        "listASC" sort A-scending | "listDESC" sort D-escending
 *              nol_Nsel        "nl_all"      all names | "A" ... "Z" name starts with ..
 */
function showNODES_nol() {
    Nol_Sorted = "listASC";                                     // sort list of names - Default: names A-scending
    Nol_Type   = "NLc";                                         // default: list by names
    parms.lSET("nol-Type", Nol_Type);
    parms.lSET("nol-Sort", Nol_Sorted);
    parms.lSET("nol-Nsel", i18n('nl_all'));                     // default: full nodeslist

    nol_arr = C_NODESman.get_Ynarr().toSorted();                // get the list of names (array) in data

    const _names = document.getElementById("nodes_sel").children[0];        // target HTML-element
    nolNames = _names.value;

    const C_liHead = document.getElementById("nodes_liHead");                // reset nodes_list
    C_liHead.innerHTML = "";

    const C_liLines = document.getElementById("nodes_liLines");              // reset nodes_list
    C_liLines.innerHTML = "";

    let _nls = parms.lGET("NODES_LIST_size");
    if (nol_arr.length > _nls) {
        make_noli_Head(C_liHead);
    }

    nol_build();

    // make list visible
    document.querySelector("#nodeslist").style.display = "block";
}

/**
 * 
 * @param {*} event 
 */
function NodeList_click(event) {
    let elA = event.target;
    let nKey = elA.textContent;
    let Ynode = C_NODESman.get_Ynodes(nKey);
    if (elA.classList.contains('selectedID')) {       // List-element already selected
        elA.classList.remove('selectedID');                 // remove selection
        Ynode.sr = 1; Ynode.fx = null; Ynode.fy = null;
        if (Ynode.is_focus)
            make_Focus_Node(Ynode);
        switch_clearSI(- 1);
        return false;
    }
    elA.classList.add("selectedID");
    Ynode.sr = nodeMagnifier; Ynode.fx = Ynode.x; Ynode.fy = Ynode.y;
    switch_clearSI(1);
}
function switch_clearSI(_x) {
    cnt_sel_ID += _x;
    if (cnt_sel_ID > 1) return false;
    let btn_selID = document.getElementById("clearSI");
    if (cnt_sel_ID < 1) {
        btn_selID.disabled = true;
        return true;
    }
    if (cnt_sel_ID == 1) {
        btn_selID.disabled = false;
        return false;
    }
}

// Set target as Focus_Node
function NodeList_dblclick(event) {
    let linObj = parms.oGET("RENDERER");

    let elA = event.target;
    let nKey = elA.textContent;
    let fN_reset = false;
    if (elA.classList.contains('nol-focus-node'))  {       // List-element already selected
        fN_reset = true;
    }
    let Ynode = C_NODESman.get_Ynodes(nKey);

    let fN_old = document.getElementsByClassName('nol-focus-node')[0];
    if (fN_old) {
        fN_old.classList.remove('nol-focus-node');                 // remove selection
    }
    let Focus_Node = C_NODESman.Focus_Node;
    if (Focus_Node) {
        Focus_Node.sr = 1; Focus_Node.fx = null; Focus_Node.fy = null; Focus_Node.is_focus = false;
    }

    let _nol_fN = document.getElementById("nodes_sel").firstElementChild;
    if (fN_reset) {
        if (!_nol_fN.classList.contains('placeholder')) {_nol_fN.classList.toggle('placeholder')};
        _nol_fN.textContent = i18n('nol_placeholder');
        C_NODESman.Focus_Node = null;
        return false;
    }
    let fN_key = Ynode.m_key;
    _nol_fN.textContent = fN_key;
    if (_nol_fN.classList.contains('placeholder')) {_nol_fN.classList.toggle('placeholder')};

    Ynode.is_focus = true;
    C_NODESman.Focus_Node = Ynode;
    linObj.Focus_Node = Ynode;
    
    elA.classList.add("nol-focus-node");
    make_Focus_Node(Ynode);

    linObj.YearedData = linObj.DATAman.makeYearedData(linObj);
    linObj.yNODES = linObj.YearedData.nodes;
    linObj.yLINKS = linObj.YearedData.links;
    linObj.forceRefresh = true;                        // ev. weitere nodes relevant -> neu aufbauen
    console.log('loop-forceRefresh true');
    parms.dataMod(true);

    C_NODESman.set_Ynlist(linObj.yNODES);
    
    return true;    
}

