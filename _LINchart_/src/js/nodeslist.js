function nol_content(event) {
    let actE = event.target;
    let _type = parms.lGET("nol-Type");
    if (actE.value == _type) {
        return false;
    }
    _type = actE.value;
    Nol_Type = _type;
    parms.lSET("nol-Type", _type);
    nol_fill_do();
    return true;
}

function nol_fill(event) {
    let actE = event.target;
    let _fmode = parms.lGET("nol-Nsel");
    if (actE.value == _fmode) {
        return false;
    }
    _fmode = actE.value;
    parms.lSET("nol-Nsel", _fmode);
    nol_fill_do();
    return true;
}

function nol_fill_do() {
    let _fmode = parms.lGET("nol-Nsel");
    let _type = parms.lGET("nol-Type");
    if (_fmode == i18n('nl_all')) {
        nol_arr = C_NODESman.get_Ynarr_type(_type).toSorted();                 // get the list of names in data
    } else {
        let nol_list = C_NODESman.get_YnodesN0(_fmode);
        nol_arr = nol_list.split(';').toSorted();
    }
    nol_build();
}

function nol_rebuild(event) {
    let actE = event.target;
    let _smode = parms.lGET("nol-Sort");
    if (actE.value == _smode) {
        return false;
    }
    _smode = actE.value;
    parms.lSET("nol-Sort", _smode);
    nol_build();
    return true;
}

function nol_build() {
    let _smode = parms.lGET("nol-Sort");
    let _type = parms.lGET("nol-Type");
    let _fmode = parms.lGET("nol-Nsel");

    let _nol_fN = document.getElementById("nodes_sel").firstElementChild;
    _nol_fN.textContent = i18n('nol_placeholder');
    if (!_nol_fN.classList.contains('placeholder')) {_nol_fN.classList.toggle('placeholder');}

    let Focus_Node = C_NODESman.Focus_Node;
    let fN_key = '';
    if (Focus_Node) {
        fN_key = Focus_Node.m_key;
        _nol_fN.textContent = fN_key;
        _nol_fN.classList.toggle('placeholder');
    }
    const C_liLines = document.getElementById("nodes_liLines");                    // reset nodes_list
    C_liLines.innerHTML = "";
    if (_smode != Nol_Sorted) {
        nol_arr = nol_arr.reverse();
        Nol_Sorted = _smode;
    }
    if (_type == "NLc") {
        make_noli_Lines_NLc(C_liLines, fN_key);
    } else {
        make_noli_Lines_NLy(C_liLines, fN_key);
    }
    showNODES_ul_li();
}

/**
 * Nodes simply ordered by Name
 * <ul>                     -> _liL_NLc
 *  <li>...</li>                -> liItem
 * </ul>
 */
function make_noli_Lines_NLc(_liLines, fN_key) {
    let _liL_NLc = document.createElement("ul");

    nol_arr.forEach(function(key) {
        if (key > "") {
            // console.log(key + ' = ' + value);
            // make a HTML-'li'
            let liItem = document.createElement("li");
            liItem.classList = 'nol-ulli';
            liItem.textContent = key;
            if (key == fN_key)
                liItem.classList.add('nol-focus-node');
            //Append the <li> to the <ul>
            _liL_NLc.appendChild(liItem);
        }
    });

    _liLines.appendChild(_liL_NLc);
}
/**
 * Nodes ordered by year(-ranged by 10-) and name
 * <div>                     -> _liL_NLy
 *   <ul>                           -> _liL_ul
 *    <li>...</li>                      -> liItem
 *   </ul>
 * </div>
 */
function make_noli_Lines_NLy(_liLines, fN_key) {
    let _liL_NLy = null;
    let _li_year = '';
    let _liL_ul = null;

    nol_arr.forEach(function(key) {
        if (key > "") {
            let _year = key.substr(0, 4);
            let _key = key.substr(5);
            if (_year != _li_year) {
                if (_li_year > '') {
                    _liL_NLy.appendChild(_liL_ul);
                    _liLines.appendChild(_liL_NLy);
                }
                _liL_NLy = document.createElement("div");
                _liL_NLy.className = "NLy-year";
                let _liL_year = document.createElement("span");
                _liL_year.textContent = _year;
                _liL_NLy.appendChild(_liL_year);
                _li_year = _year;
                _liL_ul = document.createElement("ul");
            }
            // make a HTML-'li'
            let liItem = document.createElement("li");
            liItem.classList = 'nol-ulli';
            liItem.textContent = _key;
            if (_key == fN_key)
                liItem.classList.add('nol-focus-node');
            //Append the <li> to the <ul>
            _liL_ul.appendChild(liItem);
        }
    });

    _liL_NLy.appendChild(_liL_ul);
    _liLines.appendChild(_liL_NLy);
}

function drag_nol(elmnt) {
    let pos1 = 0, pos2 = 0, pos3 = 0, pos4 = 0;
    let win_iH = window.innerHeight;     let win_iW = window.innerWidth;
    // if (document.getElementById(elmnt.id + "header")) {
    //     // the header is where you move the DIV from:
    //     document.getElementById(elmnt.id + "header").onmousedown = dragMouseDown;
    // } else {
        // otherwise, move the DIV from anywhere inside the DIV:
        elmnt.onmousedown = dragMouseDown;
    // }

    function dragMouseDown(e) {
        // e = e || window.event;
        e.preventDefault();
        // get the mouse cursor position at startup:
        pos3 = e.clientX;
        pos4 = e.clientY;
        document.onmouseup = closeDragElement;
        // call a function whenever the cursor moves:
        document.onmousemove = elementDrag;
    }

    function elementDrag(e) {
        // e = e || window.event;
        e.preventDefault();
        // calculate the new cursor position:
        pos1 = pos3 - e.clientX;
        pos2 = pos4 - e.clientY;
        pos3 = e.clientX;
        pos4 = e.clientY;
        // set the element's new position:
        let _top = elmnt.offsetTop - pos2;
        if (_top < 1) { _top = 1; }
        if (_top > win_iH) { _top = (win_iH - 24);}
        let _left = elmnt.offsetLeft - pos1;
        if (_left < 1) { _left = 1; }
        if (_left > (win_iW - elmnt.offsetWidth)) { _left = (win_iW - elmnt.offsetWidth);}
        elmnt.style.top = _top + "px";
        elmnt.style.left = _left + "px";
    }

    function closeDragElement() {
        // stop moving when mouse button is released:
        document.onmouseup = null;
        document.onmousemove = null;
    }
}

